// Rebuild the committed homepage assets after changing its copy or studio screenshot.
// Run: node --import tsx scripts/build-home-assets.mjs
// Requires fonttools with Brotli support (pyftsubset) and ffmpeg with libwebp.
// These tools are only needed to regenerate assets, never to build or serve the app.
import { execFileSync } from 'node:child_process';
import { copyFile, mkdir, mkdtemp, rm, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LANDING_COPY } from '../src/ui/landing-copy.ts';
import { pageCopy } from '../src/locale.ts';

const root = fileURLToPath(new URL('../', import.meta.url));
const assets = join(root, 'src/assets');
const fonts = join(root, 'node_modules/@fontsource/noto-sans-jp');
const temporary = await mkdtemp(join(tmpdir(), 'poietra-home-assets-'));
function strings(value) {
  return typeof value === 'string' ? [value] : Object.values(value).flatMap(strings);
}
const characters = [...new Set(strings({ LANDING_COPY, pageCopy }).join(''))]
  .filter(character => character.codePointAt(0) > 255)
  .sort((a, b) => a.codePointAt(0) - b.codePointAt(0));
try {
  await mkdir(assets, { recursive: true });
  const text = join(temporary, 'characters.txt');
  await writeFile(text, characters.join(''));
  const output = join(assets, 'home-noto-ja.woff2');
  execFileSync('pyftsubset', [join(fonts, 'files/noto-sans-jp-japanese-400-normal.woff2'), `--text-file=${text}`, `--output-file=${output}`, '--flavor=woff2', '--layout-features=*', '--no-recalc-timestamp', '--canonical-order'], { stdio: 'inherit' });
  await copyFile(join(fonts, 'LICENSE'), join(assets, 'home-noto-ja.LICENSE.txt'));
  const inter = [400, 500, 600].map(weight => `@font-face { font-family: Inter; font-style: normal; font-display: swap; font-weight: ${weight}; src: url('../node_modules/@fontsource/inter/files/inter-latin-${weight}-normal.woff2') format('woff2'); }`).join('\n');
  const ranges = characters.map(character => `U+${character.codePointAt(0).toString(16).toUpperCase()}`).join(',');
  await writeFile(join(root, 'src/home-fonts.css'), `/* Generated by scripts/build-home-assets.mjs. Full editor fonts load separately. */\n${inter}\n@font-face { font-family: 'Noto Sans JP'; font-style: normal; font-display: swap; font-weight: 400; src: url('./assets/home-noto-ja.woff2') format('woff2'); unicode-range: ${ranges}; }\n`);
  console.log(`Homepage Japanese: ${characters.length} characters, ${(await stat(output)).size} bytes`);

  // Lossless WebP preserves the screenshot. A smaller source saves mobile transfers.
  for (const width of [720, 1440]) {
    const destination = join(root, `public/studio-preview-${width}.webp`);
    execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-i', join(root, 'public/studio-preview.png'), ...(width === 1440 ? [] : ['-vf', `scale=${width}:-1:flags=lanczos`]), '-frames:v', '1', '-c:v', 'libwebp', '-lossless', '1', '-compression_level', '6', destination], { stdio: 'inherit' });
    console.log(`Studio preview ${width}: ${(await stat(destination)).size} bytes`);
  }
} finally { await rm(temporary, { recursive: true, force: true }); }
